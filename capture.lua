local db = require("ClipHistory.db")
local config = require("ClipHistory.config")

local M = {}
local log = hs.logger.new("ClipHistory", "info")
local watcher
local ignoreCount

local CONCEALED = {
  ["org.nspasteboard.ConcealedType"] = true,
  ["org.nspasteboard.TransientType"] = true,
  ["org.nspasteboard.AutoGeneratedType"] = true,
}

local function isBlank(s)
  return (s:gsub("%s", ""):gsub("\194\160", ""):gsub("\227\128\128", "")) == ""
end

local function isConcealed()
  for _, uti in ipairs(hs.pasteboard.contentTypes() or {}) do
    if CONCEALED[uti] then return true end
  end
  return false
end

local function frontmostSource()
  local app = hs.application.frontmostApplication()
  if not app then return nil, nil end
  return app:bundleID(), app:name()
end

local function handle()
  local count = hs.pasteboard.changeCount()
  if ignoreCount and count == ignoreCount then
    ignoreCount = nil
    return
  end

  if isConcealed() then return end

  local body = hs.pasteboard.readString()
  if not body or body == "" or isBlank(body) or #body > config.maxItemBytes then return end

  local bundle, name = frontmostSource()
  local id, err = db.insert({ body = body, src_bundle = bundle, src_name = name })
  if id then
    M.lastId = id
  else
    log.e("insert failed: " .. tostring(err))
  end
end

function M.start()
  if watcher then return end
  watcher = hs.pasteboard.watcher.new(handle)
  watcher:start()
end

function M.stop()
  if watcher then
    watcher:stop()
    watcher = nil
  end
end

function M.markSelfWrite()
  ignoreCount = hs.pasteboard.changeCount()
end

return M
